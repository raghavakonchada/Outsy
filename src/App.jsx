import React, { useState, useEffect } from 'react';
import Navbar from './components/Navbar';
import Hero from './components/Hero';
import MissionCard from './components/MissionCard';
import ActivityCards from './components/ActivityCards';
import HowItWorks from './components/HowItWorks';
import ProgressSection from './components/ProgressSection';
import Footer from './components/Footer';
import { missionEngine } from './engine';
import './App.css';

function App() {
  // Available filter states
  const [activeCategoryFilter, setActiveCategoryFilter] = useState('all');
  const [activeTimeFilter, setActiveTimeFilter] = useState('any');

  // Initialize with a rich mission generated by the rule-based engine
  const [currentMission, setCurrentMission] = useState(() => {
    return missionEngine.generateMission({
      category: 'all',
      availableTime: 'any',
    });
  });

  // Real application state: list of missions actually completed by the user
  const [completedMissions, setCompletedMissions] = useState(() => {
    try {
      const saved = localStorage.getItem('outsy_completed_missions');
      return saved ? JSON.parse(saved) : [];
    } catch {
      return [];
    }
  });

  // Check if current displayed mission is marked completed
  const isCompleted = Boolean(
    currentMission && completedMissions.some((m) => m.id === currentMission.id)
  );

  // Sync real completed missions array to localStorage
  useEffect(() => {
    try {
      localStorage.setItem('outsy_completed_missions', JSON.stringify(completedMissions));
    } catch {
      // Graceful fallback if localStorage is disabled
    }
  }, [completedMissions]);

  /**
   * Modular mission generation handler.
   * Invokes the mission engine with active criteria and previous mission exclusion.
   */
  const handleGenerateMission = (
    category = activeCategoryFilter,
    time = activeTimeFilter
  ) => {
    const nextMission = missionEngine.generateMission({
      category,
      availableTime: time,
      excludeId: currentMission?.id,
    });
    setCurrentMission(nextMission);
  };

  // Toggle mission completion state authentically
  const handleToggleComplete = () => {
    if (!currentMission) return;

    if (!isCompleted) {
      const now = new Date();
      const timeString = now.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
      const completedEntry = {
        ...currentMission,
        completedAt: timeString,
      };
      setCompletedMissions((prev) => [
        completedEntry,
        ...prev.filter((m) => m.id !== currentMission.id),
      ]);
    } else {
      setCompletedMissions((prev) => prev.filter((m) => m.id !== currentMission.id));
    }
  };

  // Select category filter and immediately pull an aligned mission
  const handleSelectCategory = (categoryId) => {
    setActiveCategoryFilter(categoryId);
    handleGenerateMission(categoryId, activeTimeFilter);
  };

  // Select available time filter and immediately pull an aligned mission
  const handleSelectTimeFilter = (timeId) => {
    setActiveTimeFilter(timeId);
    handleGenerateMission(activeCategoryFilter, timeId);
  };

  // Clear / reset session practice log
  const handleResetProgress = () => {
    if (window.confirm('Reset your outdoor practice log for this session?')) {
      setCompletedMissions([]);
    }
  };

  return (
    <div className="outsy-adventure-app">
      <Navbar onGetMission={() => handleGenerateMission()} />
      <main id="main-content">
        <Hero 
          onGetMission={() => handleGenerateMission()} 
          currentMission={currentMission}
        />

        <MissionCard
          currentMission={currentMission}
          onGetRandomMission={() => handleGenerateMission()}
          isCompleted={isCompleted}
          onToggleComplete={handleToggleComplete}
          activeCategoryFilter={activeCategoryFilter}
          onSelectCategory={handleSelectCategory}
          activeTimeFilter={activeTimeFilter}
          onSelectTimeFilter={handleSelectTimeFilter}
        />

        <ActivityCards onPickCategory={handleSelectCategory} />

        <HowItWorks onGetMission={() => handleGenerateMission()} />

        <ProgressSection 
          completedMissions={completedMissions}
          onResetProgress={handleResetProgress}
          onTakeMission={() => handleGenerateMission()}
        />
      </main>

      <Footer onGetMission={() => handleGenerateMission()} />
    </div>
  );
}

export default App;
